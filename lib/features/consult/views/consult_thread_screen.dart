/// One consultation thread — shared by the parent and the doctor.
/// Whose-side a bubble sits on depends on who is viewing.
class ConsultThreadScreen extends ConsumerStatefulWidget {
  final String consultId;
  const ConsultThreadScreen({super.key, required this.consultId});

  @override
  ConsumerState<ConsultThreadScreen> createState() =>
      _ConsultThreadScreenState();
}

class _ConsultThreadScreenState extends ConsumerState<ConsultThreadScreen> {
  final _controller = TextEditingController();
  bool _sending = false;

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  Future<void> _send({File? photo}) async {
    final text = _controller.text.trim();
    if (text.isEmpty && photo == null) return;
    setState(() => _sending = true);
    _controller.clear();
    final ok = await ref.read(consultServiceProvider).sendMessage(
          widget.consultId,
          text: text,
          fromDoctor: isDoctorAccount,
          photo: photo,
        );
    if (!mounted) return;
    setState(() => _sending = false);
    if (!ok) {
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
        content: Text(tr(currentLang(context),
            en: 'Could not send. Try again.',
            ru: 'Не удалось отправить. Попробуй ещё раз.',
            ky: 'Жөнөтүлгөн жок. Кайра аракет кыл.')),
      ));
    }
  }

  Future<void> _attachPhoto() async {
    final file = await StorageService().showPickerSheet(context);
    if (file != null) await _send(photo: file);
  }

  void _sendFollowUp(String text) {
    if (text.isEmpty) return;
    _controller.text = text;
    _send();
  }

  @override
  Widget build(BuildContext context) {
    final messages = ref.watch(consultMessagesProvider(widget.consultId));
    final consult = ref.watch(consultationProvider(widget.consultId)).asData?.value;
    final lang = currentLang(context);
    final isDoctor = isDoctorAccount;

    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        title: Text(isDoctor
            ? tr(lang, en: 'Consultation', ru: 'Консультация', ky: 'Консультация')
            : kDoctorName),
      ),
      body: Column(
        children: [
          // Doctor-only briefing card pinned to the top of the thread.
          // The brief is server-generated by generateDoctorBrief shortly
          // after consult creation; while it's composing, nothing is
          // shown (the thread itself is still readable).
          if (isDoctor && consult?.doctorBriefSummary != null)
            _BriefCard(brief: consult!.doctorBriefSummary!, lang: lang),
          Expanded(
            child: messages.when(
              loading: () =>
                  const Center(child: CircularProgressIndicator()),
              error: (_, _) => Center(
                child: Text(tr(lang,
                    en: 'Could not load the thread.',
                    ru: 'Не удалось загрузить переписку.',
                    ky: 'Жазышуу жүктөлгөн жок.')),
              ),
              data: (msgs) => msgs.isEmpty
                  ? const SizedBox.shrink()
                  : ListView.builder(
                      reverse: true,
                      padding: const EdgeInsets.fromLTRB(12, 12, 12, 12),
                      itemCount: msgs.length,
                      itemBuilder: (context, i) {
                        final m = msgs[msgs.length - 1 - i];
                        if (m.kind == ConsultMessageKind.aiFollowupSuggestion) {
                          // Parents see the follow-up pills; doctors don't.
                          if (isDoctor) return const SizedBox.shrink();
                          return _FollowUpPills(
                            suggestions: m.suggestedFollowUps,
                            onTap: _sendFollowUp,
                            lang: lang,
                          );
                        }
                        return _Bubble(
                          message: m,
                          mine: m.fromDoctor == isDoctor,
                        );
                      },
                    ),
            ),
          ),
          _Composer(
            controller: _controller,
            sending: _sending,
            onSend: () => _send(),
            onAttach: _attachPhoto,
            hint: tr(lang,
                en: 'Write a message…',
                ru: 'Напиши сообщение…',
                ky: 'Билдирүү жаз…'),
          ),
        ],
      ),
    );
  }
}

/// Doctor-only briefing pinned above the messages. Compact, pre-formatted
/// 30-second read written by `generateDoctorBrief`. Shows nothing while
/// the brief is still composing — the messages themselves are readable.
class _BriefCard extends StatelessWidget {
  final String brief;
  final String lang;
  const _BriefCard({required this.brief, required this.lang});

  @override
  Widget build(BuildContext context) {
    return Container(
      margin: const EdgeInsets.fromLTRB(12, 12, 12, 0),
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: AppColors.primary.withValues(alpha: 0.08),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: AppColors.primary.withValues(alpha: 0.25)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              const Icon(Icons.auto_awesome,
                  size: 14, color: AppColors.primary),
              const SizedBox(width: 6),
              Text(
                tr(lang,
                    en: 'BRIEFING',
                    ru: 'СВОДКА',
                    ky: 'КЫСКАЧА'),
                style: const TextStyle(
                  fontSize: 10,
                  fontWeight: FontWeight.w800,
                  color: AppColors.primary,
                  letterSpacing: 0.6,
                ),
              ),
            ],
          ),
          const SizedBox(height: 6),
